#!/usr/bin/env python3
"""Path composition guard (C-1, MEASURING MODE — ratcheted baseline).

Inventories hand-built chain and tenant path composition in production code,
so that the number of places which compose ``<corvin_home>/tenants/<tid>/
global/.../audit.jsonl`` by hand is generated by a script rather than quoted
from memory (review R8b item 14: counts were not reproducible).

Invocation (the scanner itself spawns no process; git lists the files):
  POSIX:    scripts/path_composition_guard.sh [ARGS]
            (= git ls-files -z -- '*.py' | python3 scripts/path_composition_guard.py --files-from - -0 [ARGS])
  Windows:  git ls-files -z -- *.py | python scripts\\path_composition_guard.py --files-from - -0 [ARGS]
            (run from the repository root)

Scope — only the tracked file list given via ``--files-from``, ``*.py`` only.
Excluded (not production code):
  * any path with a ``tests`` directory component, ``test_*.py``, ``conftest.py``
    — EXCEPT the production modules in TEST_NAMED_PRODUCTION, which are scanned;
  * the top-level benchmark harnesses ``benchmark/`` and ``benchmarks/``;
  * any ``examples/`` directory;
  * the E2E fixture scripts ``scripts/e2e_*_fixture.py``.
  The rest of ``scripts/`` IS scanned: operator scripts write real paths.

Watched string: a literal (or a module/class constant holding one) that, split
on "/", has a segment ``global`` or ``tenants``, or a segment that is an audit
log file name (``audit*.jsonl`` and ``<prefix>-audit*.jsonl`` /
``<prefix>_audit*.jsonl``, e.g. ``audit.jsonl``, ``audit_trail.jsonl``,
``github-audit.jsonl``).

Findings (``kind`` in the report):
  binop         ``a / W`` or ``W / a`` where W is a watched literal, or a
                single-argument ``Path(W)`` call (``Path("tenants") / x``).
                A chain ``a / "tenants" / t / "global"`` yields one finding per
                joining step.
  os.path.join  ``os.path.join(..., W, ...)`` (also via ``from os import path``
                / ``from os.path import join`` aliases).
  Path-ctor     ``Path(a, W, ...)`` with two or more arguments, or
                ``Path("x/tenants/y")`` — one literal that is itself a joined
                path. Also PurePath / PosixPath / WindowsPath / Pure* variants.
  joinpath      ``p.joinpath(..., W, ...)`` or ``Path(W).joinpath(...)``.
  constant      any of the above whose watched operand is reached only through
                a module-level ``NAME = "..."`` or a class-level constant
                (``self.AUDIT_NAME``, ``cls.X``, ``ClassName.X`` in the same
                module). ``form`` then names the join form.
  Not resolved (stated, not hidden): constants imported from another module,
  inherited class constants, f-strings and ``str`` concatenation. The totals
  are therefore a floor.

Stable key: ``<repo-relative file>::<enclosing qualname>::<normalised expr>``
(qualname ``Class.method`` / ``func`` / ``<module>``; expression =
``ast.unparse`` with whitespace collapsed). Line numbers are reported but not
keyed, so inserting lines above a finding does not change it. The count of a
key is the number of findings sharing it.

Baseline ``{key: {"count": int, "reason": str, "history"?: [{count, reason}]}}``.

Modes:
  (default)          print the JSON report (with --report: write it there and
                     print a summary)
  --check            exit 1 on: a new key; a count that rose; a count that fell
                     (shrink the baseline in the same commit); a baseline key no
                     longer found; an empty reason; an unparseable file; a
                     tracked file missing in the working tree. A STALE and a NEW
                     key in the same file with the same expression and count are
                     reported as a possible rename, with the exact command.
  --write-baseline   SHRINK-ONLY by default: drops stale keys and lowers counts.
                     It REFUSES (exit 1, nothing written) a new key or a rising
                     count unless that key is accepted explicitly:
                       --accept KEY --reason TEXT   (repeatable, paired in order)
                       --accept-file PATH           JSON {key: reason}
                     Accepting a rise keeps the old count and reason in the
                     entry's ``history`` list. An empty reason is refused.

Exit codes: 0 ok, 1 check failed / refused, 2 usage error.
"""
from __future__ import annotations

import argparse
import ast
import json
import re
import shlex
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

TENANT_SEGMENTS = frozenset({"global", "tenants"})
_AUDIT_NAME_RE = re.compile(r"^(?:.*[-_])?audit[^/]*\.jsonl$")
PATH_CTORS = frozenset({"Path", "PurePath", "PosixPath", "WindowsPath",
                        "PurePosixPath", "PureWindowsPath"})

# Production modules whose file name happens to start with ``test_``.
TEST_NAMED_PRODUCTION = frozenset({
    "core/audit/test_isolation.py",
    "core/plugins/plugin_builder/testing_framework/test_runners.py",
    "core/skills/os_skills/definition_of_done_verifier/checks/test_evidence.py",
})
EXCLUDED_TOP_DIRS = frozenset({"benchmark", "benchmarks"})
_FIXTURE_SCRIPT_RE = re.compile(r"^scripts/e2e_[^/]*_fixture\.py$")


# --------------------------------------------------------------------- scope
def is_production(rel: str) -> bool:
    if rel in TEST_NAMED_PRODUCTION:
        return True
    parts = rel.split("/")
    if "tests" in parts[:-1] or "examples" in parts[:-1]:
        return False
    if len(parts) > 1 and parts[0] in EXCLUDED_TOP_DIRS:
        return False
    if _FIXTURE_SCRIPT_RE.match(rel):
        return False
    name = parts[-1]
    if name == "conftest.py":
        return False
    if name.startswith("test_") and name.endswith(".py"):
        return False
    return True


def parse_file_list(data: bytes, nul: bool) -> list[str]:
    """Split a tracked-file list (``git ls-files`` / ``git ls-files -z``)."""
    sep = b"\0" if nul else b"\n"
    out = []
    for raw in data.split(sep):
        if not nul:
            raw = raw.strip(b"\r")
        if raw:
            out.append(raw.decode("utf-8", errors="surrogateescape"))
    return out


def read_file_list(source: str, nul: bool) -> list[str]:
    data = sys.stdin.buffer.read() if source == "-" else Path(source).read_bytes()
    return parse_file_list(data, nul)


# ------------------------------------------------------------------ matching
def is_watched_string(value: str) -> bool:
    for seg in value.replace("\\", "/").split("/"):
        if seg in TENANT_SEGMENTS or _AUDIT_NAME_RE.match(seg):
            return True
    return False


def _watched_literal(node: ast.AST) -> bool:
    return (isinstance(node, ast.Constant) and isinstance(node.value, str)
            and is_watched_string(node.value))


def _callee_name(func: ast.AST) -> str | None:
    if isinstance(func, ast.Name):
        return func.id
    if isinstance(func, ast.Attribute):
        return func.attr
    return None


def _collect_constants(tree: ast.Module) -> tuple[set[str], dict[str, set[str]]]:
    """Module-level and class-level names bound to a watched string literal."""
    module_consts: set[str] = set()
    class_consts: dict[str, set[str]] = {}

    def assigned(stmt: ast.stmt) -> list[str]:
        if isinstance(stmt, ast.Assign) and _watched_literal(stmt.value):
            return [t.id for t in stmt.targets if isinstance(t, ast.Name)]
        if (isinstance(stmt, ast.AnnAssign) and stmt.value is not None
                and _watched_literal(stmt.value) and isinstance(stmt.target, ast.Name)):
            return [stmt.target.id]
        return []

    def walk_class(cls: ast.ClassDef) -> None:
        names = class_consts.setdefault(cls.name, set())
        for stmt in cls.body:
            names.update(assigned(stmt))
            if isinstance(stmt, ast.ClassDef):
                walk_class(stmt)

    for stmt in tree.body:
        module_consts.update(assigned(stmt))
        if isinstance(stmt, ast.ClassDef):
            walk_class(stmt)
    return module_consts, class_consts


class _Finder(ast.NodeVisitor):
    def __init__(self, rel: str, tree: ast.Module) -> None:
        self.rel = rel
        self.scope: list[str] = []
        self.classes: list[str] = []
        self.findings: list[dict] = []
        self.module_consts, self.class_consts = _collect_constants(tree)
        self.ospath_aliases = {"os.path"}
        self.join_aliases: set[str] = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for a in node.names:
                    if a.name == "os.path" and a.asname:
                        self.ospath_aliases.add(a.asname)
            elif isinstance(node, ast.ImportFrom):
                if node.module == "os":
                    for a in node.names:
                        if a.name == "path":
                            self.ospath_aliases.add(a.asname or "path")
                elif node.module in ("os.path", "posixpath", "ntpath"):
                    for a in node.names:
                        if a.name == "join":
                            self.join_aliases.add(a.asname or "join")

    # ---- scopes
    def _scoped(self, node: ast.AST) -> None:
        self.scope.append(node.name)  # type: ignore[attr-defined]
        self.generic_visit(node)
        self.scope.pop()

    visit_FunctionDef = _scoped
    visit_AsyncFunctionDef = _scoped

    def visit_ClassDef(self, node: ast.ClassDef) -> None:
        self.classes.append(node.name)
        self._scoped(node)
        self.classes.pop()

    # ---- operand classification: "literal" | "constant" | None
    def _operand(self, node: ast.AST) -> str | None:
        if _watched_literal(node):
            return "literal"
        if isinstance(node, ast.Name) and node.id in self.module_consts:
            return "constant"
        if isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name):
            owner = node.value.id
            if owner in ("self", "cls") and self.classes:
                if node.attr in self.class_consts.get(self.classes[-1], ()):
                    return "constant"
            elif node.attr in self.class_consts.get(owner, ()):
                return "constant"
        if isinstance(node, ast.Call) and self._is_single_arg_ctor(node) \
                and not self._ctor_is_finding(node):
            return self._operand(node.args[0])
        return None

    def _is_single_arg_ctor(self, call: ast.Call) -> bool:
        return (_callee_name(call.func) in PATH_CTORS and len(call.args) == 1
                and not call.keywords)

    def _ctor_is_finding(self, call: ast.Call) -> bool:
        if _callee_name(call.func) not in PATH_CTORS:
            return False
        if len(call.args) >= 2:
            return any(self._operand(a) for a in call.args)
        if len(call.args) == 1:
            arg = call.args[0]
            return (_watched_literal(arg) and "/" in arg.value.replace("\\", "/"))  # type: ignore[attr-defined]
        return False

    def _is_os_path_join(self, func: ast.AST) -> bool:
        if isinstance(func, ast.Name):
            return func.id in self.join_aliases
        if isinstance(func, ast.Attribute) and func.attr == "join":
            return ast.unparse(func.value) in self.ospath_aliases
        return False

    def _record(self, node: ast.AST, form: str, via: list[str | None]) -> None:
        func = ".".join(self.scope) or "<module>"
        expr = " ".join(ast.unparse(node).split())
        kind = form if "literal" in via else "constant"
        entry = {"key": f"{self.rel}::{func}::{expr}", "file": self.rel,
                 "function": func, "expr": expr, "line": node.lineno, "kind": kind}
        if kind == "constant":
            entry["form"] = form
        self.findings.append(entry)

    # ---- join forms
    def visit_BinOp(self, node: ast.BinOp) -> None:
        if isinstance(node.op, ast.Div):
            via = [self._operand(node.left), self._operand(node.right)]
            if any(via):
                self._record(node, "binop", via)
        self.generic_visit(node)

    def visit_Call(self, node: ast.Call) -> None:
        if self._is_os_path_join(node.func):
            via = [self._operand(a) for a in node.args]
            if any(via):
                self._record(node, "os.path.join", via)
        elif _callee_name(node.func) in PATH_CTORS and self._ctor_is_finding(node):
            if len(node.args) >= 2:
                via = [self._operand(a) for a in node.args]
            else:
                via = ["literal"]
            self._record(node, "Path-ctor", via)
        elif isinstance(node.func, ast.Attribute) and node.func.attr == "joinpath":
            via = [self._operand(a) for a in node.args]
            recv = node.func.value
            if isinstance(recv, ast.Call) and self._is_single_arg_ctor(recv) \
                    and not self._ctor_is_finding(recv):
                via.append(self._operand(recv.args[0]))
            if any(via):
                self._record(node, "joinpath", via)
        self.generic_visit(node)


# ---------------------------------------------------------------------- scan
def scan(root: Path, files: list[str]) -> dict:
    """Scan the given repo-relative paths under ``root``.

    ``files`` is the tracked-file list (``git ls-files``); this function does
    not discover files itself, so nothing untracked can enter the scope.
    """
    root = Path(root).resolve()
    py_in = [r for r in files if r.endswith(".py")]
    production = sorted(set(r for r in py_in if is_production(r)))
    findings: list[dict] = []
    errors: list[dict] = []
    for rel in production:
        if rel.startswith("/") or ".." in rel.split("/"):
            errors.append({"file": rel, "error": "path is not repo-relative"})
            continue
        path = root / rel
        if not path.exists():
            errors.append({"file": rel, "error": "missing in working tree"})
            continue
        try:
            tree = ast.parse(path.read_bytes(), filename=rel)
        except (SyntaxError, ValueError) as exc:
            errors.append({"file": rel, "error": f"unparseable: {type(exc).__name__}: {exc}"})
            continue
        except OSError as exc:
            errors.append({"file": rel, "error": f"unreadable: {type(exc).__name__}: {exc}"})
            continue
        finder = _Finder(rel, tree)
        finder.visit(tree)
        findings.extend(finder.findings)
    counts: dict[str, int] = {}
    per_file: dict[str, int] = {}
    by_kind: dict[str, int] = {}
    for f in findings:
        counts[f["key"]] = counts.get(f["key"], 0) + 1
        per_file[f["file"]] = per_file.get(f["file"], 0) + 1
        by_kind[f["kind"]] = by_kind.get(f["kind"], 0) + 1
    top = sorted(per_file.items(), key=lambda kv: (-kv[1], kv[0]))[:10]
    return {
        "root": str(root),
        "files_in": len(files),
        "py_in": len(py_in),
        "excluded_py": len(py_in) - len(production),
        "production_py": len(production),
        "total_findings": len(findings),
        "keys": len(counts),
        "by_kind": dict(sorted(by_kind.items())),
        "files_with_findings": len(per_file),
        "top_files": [{"file": f, "findings": n} for f, n in top],
        "counts": dict(sorted(counts.items())),
        "findings": findings,
        "errors": errors,
    }


# ------------------------------------------------------------------ baseline
def load_baseline(path: Path) -> dict:
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def _key_file_expr(key: str) -> tuple[str, str, str]:
    file, func, expr = key.split("::", 2)
    return file, func, expr


def rename_hints(report: dict, baseline: dict) -> list[tuple[str, str]]:
    """(stale_key, new_key) pairs: same file, same expression, same count."""
    counts = report["counts"]
    stale = [k for k in baseline if k not in counts]
    new = [k for k in counts if k not in baseline]
    pairs: list[tuple[str, str]] = []
    used: set[str] = set()
    for s in stale:
        sf, _, sx = _key_file_expr(s)
        for n in new:
            if n in used:
                continue
            nf, _, nx = _key_file_expr(n)
            if sf == nf and sx == nx and counts[n] == baseline[s].get("count"):
                pairs.append((s, n))
                used.add(n)
                break
    return pairs


def _rename_command(pairs: list[tuple[str, str]], baseline: dict) -> str:
    parts = ["scripts/path_composition_guard.sh", "--write-baseline"]
    for old, new in pairs:
        reason = str(baseline[old].get("reason", "")).strip()
        parts += ["--accept", shlex.quote(new), "--reason", shlex.quote(reason)]
    return " ".join(parts)


def check(report: dict, baseline: dict) -> list[str]:
    problems: list[str] = []
    counts = report["counts"]
    for err in report["errors"]:
        problems.append(f"{err['error']}: {err['file']}")
    for key, cur in counts.items():
        if key not in baseline:
            problems.append(f"NEW key (count {cur}): {key}")
    for key, entry in baseline.items():
        if not isinstance(entry, dict) or not isinstance(entry.get("count"), int):
            problems.append(f"malformed baseline entry: {key}")
            continue
        if not str(entry.get("reason", "")).strip():
            problems.append(f"empty reason: {key}")
        if key not in counts:
            problems.append(f"STALE key (no longer found, remove it): {key}")
            continue
        cur = counts[key]
        if cur > entry["count"]:
            problems.append(f"count rose {entry['count']} -> {cur}: {key}")
        elif cur < entry["count"]:
            problems.append(f"count fell {entry['count']} -> {cur}, shrink the baseline "
                            f"(--write-baseline): {key}")
    pairs = rename_hints(report, baseline)
    for old, new in pairs:
        problems.append(f"possible rename: {old}  ->  {new}")
    if pairs:
        problems.append("carry the reasons over with: " + _rename_command(pairs, baseline))
    return problems


def regenerate(report: dict, old: dict, accepted: dict[str, str]) -> tuple[dict, list[str]]:
    """Shrink-only regeneration. Returns (new baseline, refusals)."""
    refusals: list[str] = []
    for key, reason in accepted.items():
        if not str(reason).strip():
            refusals.append(f"empty reason for accepted key: {key}")
    new: dict[str, dict] = {}
    for key, cur in report["counts"].items():
        if key in old:
            entry = dict(old[key])
            if cur > entry.get("count", 0):
                if key not in accepted:
                    refusals.append(f"count rose {entry.get('count')} -> {cur} "
                                    f"(needs --accept KEY --reason TEXT): {key}")
                    continue
                history = list(entry.get("history", []))
                history.append({"count": entry.get("count"), "reason": entry.get("reason", "")})
                entry = {"count": cur, "reason": accepted[key].strip(), "history": history}
            else:
                entry["count"] = cur
            new[key] = entry
        else:
            if key not in accepted:
                refusals.append(f"NEW key (count {cur}, needs --accept KEY --reason TEXT): {key}")
                continue
            new[key] = {"count": cur, "reason": accepted[key].strip()}
    for key in accepted:
        if key not in report["counts"]:
            refusals.append(f"accepted key not found in the scan: {key}")
    return new, refusals


def _write_json(path: Path, data: dict) -> None:
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False, sort_keys=True) + "\n",
                    encoding="utf-8")


def _summary(report: dict) -> str:
    kinds = ", ".join(f"{k} {v}" for k, v in report["by_kind"].items()) or "none"
    return (f"path-composition-guard: files in {report['files_in']} "
            f"(.py {report['py_in']}, excluded {report['excluded_py']}, "
            f"production {report['production_py']}); findings {report['total_findings']} "
            f"[{kinds}], keys {report['keys']}, file errors {len(report['errors'])}")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--root", type=Path, default=REPO_ROOT,
                    help="directory the listed paths are relative to (default: this checkout)")
    ap.add_argument("--files-from", required=True,
                    help="tracked-file list (git ls-files output); '-' reads stdin")
    ap.add_argument("-0", dest="nul", action="store_true",
                    help="the file list is NUL-separated (git ls-files -z)")
    ap.add_argument("--baseline", type=Path, default=None,
                    help="baseline JSON (default: <root>/scripts/path_composition_baseline.json)")
    ap.add_argument("--report", type=Path, default=None, help="write the JSON report here")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--write-baseline", action="store_true")
    ap.add_argument("--accept", action="append", default=[], metavar="KEY")
    ap.add_argument("--reason", action="append", default=[], metavar="TEXT",
                    help="reason for the --accept at the same position")
    ap.add_argument("--accept-file", type=Path, default=None,
                    help="JSON object {key: reason} of keys to accept")
    args = ap.parse_args(argv)

    if args.write_baseline and args.check:
        ap.error("--write-baseline and --check are mutually exclusive")
    if (args.accept or args.reason or args.accept_file) and not args.write_baseline:
        ap.error("--accept/--reason/--accept-file only apply to --write-baseline")
    if len(args.accept) != len(args.reason):
        ap.error("every --accept KEY needs its own --reason TEXT")

    root = args.root.resolve()
    baseline_path = args.baseline or (root / "scripts" / "path_composition_baseline.json")
    report = scan(root, read_file_list(args.files_from, args.nul))
    if args.report:
        args.report.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n",
                               encoding="utf-8")

    if args.write_baseline:
        accepted: dict[str, str] = {}
        if args.accept_file:
            data = json.loads(args.accept_file.read_text(encoding="utf-8"))
            if not isinstance(data, dict):
                ap.error("--accept-file must hold a JSON object {key: reason}")
            accepted.update({str(k): str(v) for k, v in data.items()})
        accepted.update(dict(zip(args.accept, args.reason)))
        old = load_baseline(baseline_path)
        new, refusals = regenerate(report, old, accepted)
        print(_summary(report))
        if report["errors"]:
            refusals += [f"{e['error']}: {e['file']}" for e in report["errors"]]
        if refusals:
            for r in refusals:
                print(f"REFUSED {r}", file=sys.stderr)
            pairs = rename_hints(report, old)
            for o, n in pairs:
                print(f"possible rename: {o}  ->  {n}", file=sys.stderr)
            if pairs:
                print("carry the reasons over with: " + _rename_command(pairs, old),
                      file=sys.stderr)
            print(f"path-composition-guard: baseline NOT written, {len(refusals)} refusal(s)",
                  file=sys.stderr)
            return 1
        dropped = len([k for k in old if k not in new])
        _write_json(baseline_path, new)
        print(f"baseline written: {baseline_path} ({len(new)} keys, {dropped} dropped, "
              f"{len(accepted)} accepted)")
        return 0

    if args.check:
        problems = check(report, load_baseline(baseline_path))
        print(_summary(report))
        if problems:
            for p in problems:
                print(f"FAIL {p}", file=sys.stderr)
            print(f"path-composition-guard: {len(problems)} problem(s)", file=sys.stderr)
            return 1
        print("path-composition-guard: check OK")
        return 0

    if args.report:
        print(_summary(report))
        for t in report["top_files"]:
            print(f"  {t['findings']:5d}  {t['file']}")
    else:
        print(json.dumps(report, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
