def _to_pascal_case(snake_case: str) -> str:
    """Convert snake_case to PascalCase."""
    return "".join(word.capitalize() for word in snake_case.split("_"))


def test_gate2_e2e_skill_forge_v2_full_pipeline():
    """
    GATE 2 E2E PROOF: Full Skill Forge v2.0 Pipeline

    Phases:
    1. Generate a real Skill folder (Phase 1-2 output)
    2. Package to ZIP (SkillPackager)
    3. Extract & validate ZIP
    4. Load the Skill
    5. Execute the Skill
    6. Verify audit events
    """

    print("\n" + "=" * 80)
    print("GATE 2 E2E PROOF: Skill Forge v2.0 Full Pipeline")
    print("=" * 80)

    skill_id = "e2e_test_skill_router"
    skill_name = "E2E Test Skill Router"
    skill_version = "1.0.0"

    # ========================================================================
    # PHASE 1: Generate Real Skill Folder
    # ========================================================================

    print_step(1, "Generate Real Skill Folder (Phase 1-2 Output)")

    with tempfile.TemporaryDirectory() as tmpdir:
        tmpdir_path = Path(tmpdir)

        # Generate the skill
        generator = RealSkillGenerator()
        skill_folder = generator.generate_skill_folder(
            tmpdir_path,
            skill_id=skill_id,
            name=skill_name,
            version=skill_version,
            description="E2E test skill for Gate 2 proof.",
        )

        print_success(f"Skill folder created at: {skill_folder.name}/")
        print_info(f"  Structure: src/, hooks/, tests/, scripts/, docs/, .forge/")
        print_info(f"  Files: skill.json, README.md, .forge/generation_context.json, audit_trail.jsonl")

        # ====================================================================
        # PHASE 2: Package Skill to ZIP
        # ====================================================================

        print_step(2, "Package Skill to ZIP (SkillPackager)")

        # Load manifest
        manifest_data = json.loads((skill_folder / "skill.json").read_text())
        manifest = SkillManifestV2.from_dict(manifest_data)
        print_success(f"Loaded manifest: {manifest.skill_id} v{manifest.version}")

        # Package skill
        output_dir = tmpdir_path / "packages"
        packager = SkillPackager(output_dir)

        zip_path, zip_hash, metadata = packager.package(skill_folder, manifest)

        print_success(f"Skill packaged: {zip_path.name}")
        print_info(f"  ZIP hash: {zip_hash[:20]}...")
        print_info(f"  File count: {metadata['checksum_count']}")
        print_info(f"  Audit events: {metadata['audit_trail_events']}")
        print_info(f"  Generated at: {metadata['packaged_at']}")

        # Verify ZIP exists
        assert zip_path.exists(), f"ZIP not created: {zip_path}"
        print_success(f"ZIP file verified: {zip_path.stat().st_size} bytes")

        # ====================================================================
        # PHASE 3: Extract & Validate ZIP
        # ====================================================================

        print_step(3, "Extract & Validate ZIP")

        extract_dir = tmpdir_path / "extracted"
        extract_dir.mkdir()

        with zipfile.ZipFile(zip_path, "r") as zf:
            zf.extractall(extract_dir)
            file_list = zf.namelist()

        print_success(f"ZIP extracted: {len(file_list)} files")
        print_info(f"  Top-level: {list(set(f.split('/')[0] for f in file_list))}")

        # Verify key files
        extracted_skill_dir = extract_dir / skill_id
        expected_files = [
            "skill.json",
            "README.md",
            "src/skill.py",
            ".forge/generation_context.json",
            ".forge/audit_trail.jsonl",
            ".forge/checksum.sha256",
        ]

        for expected_file in expected_files:
            file_path = extracted_skill_dir / expected_file
            assert file_path.exists(), f"Missing file: {expected_file}"
            print_success(f"✓ {expected_file}")

        # Verify checksums
        checksum_file = extracted_skill_dir / ".forge" / "checksum.sha256"
        checksum_content = checksum_file.read_text()
        checksum_lines = [line for line in checksum_content.strip().split("\n") if line]
        print_success(f"Checksums verified: {len(checksum_lines)} files checksummed")
        print_info(f"  Format: sha256:<hash> <path>")

        # Verify generation_context
        context_file = extracted_skill_dir / ".forge" / "generation_context.json"
        context = json.loads(context_file.read_text())
        print_success(f"Generation context loaded:")
        print_info(f"  skill_id: {context['skill_id']}")
        print_info(f"  version: {context['version']}")
        print_info(f"  phases: {', '.join(context['phases_completed'])}")

        # Verify audit_trail
        audit_file = extracted_skill_dir / ".forge" / "audit_trail.jsonl"
        audit_events = [json.loads(line) for line in audit_file.read_text().strip().split("\n") if line]
        print_success(f"Audit trail loaded: {len(audit_events)} events")
        for event in audit_events:
            print_info(f"  • {event.get('event')} (phase {event.get('phase', '?')})")

        # ====================================================================
        # PHASE 4: Load the Skill
        # ====================================================================

        print_step(4, "Load & Instantiate Skill")

        # Add extracted skill to sys.path
        sys.path.insert(0, str(extracted_skill_dir))

        # Import the skill module
        skill_module_path = extracted_skill_dir / "src" / "skill.py"
        assert skill_module_path.exists(), f"Skill module not found: {skill_module_path}"

        spec = importlib.util.spec_from_file_location("skill_module", skill_module_path)
        skill_module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(skill_module)

        print_success(f"Skill module loaded: {skill_module.__name__}")

        # Instantiate the Skill
        skill_class_name = _to_pascal_case(skill_id) + "Skill"
        assert hasattr(skill_module, skill_class_name), f"Class not found: {skill_class_name}"

        skill_class = getattr(skill_module, skill_class_name)
        skill_instance = skill_class()

        print_success(f"Skill instantiated: {skill_class_name}")
        print_info(f"  Instance created at: {skill_instance.created_at}")
        print_info(f"  Execution count: {skill_instance.execution_count}")

        # ====================================================================
        # PHASE 5: Execute the Skill
        # ====================================================================

        print_step(5, "Execute Skill & Capture Output")

        test_inputs = [
            "test request 1",
            "test request 2",
            "test request 3",
        ]

        execution_results = []

        for i, test_input in enumerate(test_inputs, 1):
            result = skill_instance.execute(test_input)

            # Verify result structure
            assert isinstance(result, dict), f"Result must be dict, got {type(result)}"
            assert "output" in result, "Missing 'output' in result"
            assert "confidence" in result, "Missing 'confidence' in result"
            assert "execution_count" in result, "Missing 'execution_count' in result"
            assert "timestamp" in result, "Missing 'timestamp' in result"

            execution_results.append(result)

            print_success(f"Execution {i}: {test_input}")
            print_info(f"  output: {result['output']}")
            print_info(f"  confidence: {result['confidence']:.2f}")
            print_info(f"  execution_count: {result['execution_count']}")

        assert skill_instance.execution_count == 3, "Execution count should be 3"
        print_success(f"All {len(test_inputs)} executions completed successfully")

        # Verify confidence increases
        confidences = [r["confidence"] for r in execution_results]
        assert all(confidences[i] <= confidences[i + 1] for i in range(len(confidences) - 1)), \
            "Confidence should increase with executions"
        print_info(f"  Confidence progression: {[f'{c:.2f}' for c in confidences]}")

        # ====================================================================
        # PHASE 6: Verify Audit Trail & Chain Integrity
        # ====================================================================

        print_step(6, "Verify Audit Trail & Chain Integrity")

        print_success(f"Audit trail file: {audit_file}")
        print_info(f"  Events in ZIP: {len(audit_events)}")

        # Verify each audit event
        for i, event in enumerate(audit_events):
            assert "timestamp" in event, f"Missing timestamp in event {i}"
            assert "event" in event, f"Missing event type in event {i}"
            assert "skill_id" in event, f"Missing skill_id in event {i}"
            print_success(f"Event {i+1}: {event['event']}")
            print_info(f"    timestamp: {event['timestamp']}")
            print_info(f"    skill_id: {event['skill_id']}")

        # Verify manifest is hashable (for audit integrity)
        manifest_json = json.dumps(manifest_data, sort_keys=True)
        manifest_hash = hashlib.sha256(manifest_json.encode()).hexdigest()
        print_success(f"Manifest integrity hash: sha256:{manifest_hash[:16]}...")

        # ====================================================================
        # FINAL VERIFICATION
        # ====================================================================

        print_step(7, "Final Verification & Summary")

        # Checklist
        checks = {
            "✓ Real Skill folder generated": skill_folder.exists(),
            "✓ ZIP created with correct name": zip_path.exists(),
            "✓ ZIP contains all required files": all(
                (extracted_skill_dir / f).exists() for f in expected_files
            ),
            "✓ Manifest loaded successfully": manifest.skill_id == skill_id,
            "✓ Skill module imported": "skill_module" in locals(),
            "✓ Skill instantiated": skill_instance is not None,
            "✓ Skill executed 3 times": skill_instance.execution_count == 3,
            "✓ Output structure valid": all(
                all(k in r for k in ["output", "confidence", "execution_count"])
                for r in execution_results
            ),
            "✓ Audit events present": len(audit_events) >= 2,
            "✓ Checksums computed": len(checksum_lines) > 0,
        }

        all_passed = True
        for check, passed in checks.items():
            if passed:
                print_success(check)
            else:
                print_error(check)
                all_passed = False

        # Print summary
        print("\n" + "=" * 80)
        print(f"GATE 2 PROOF COMPLETE: {'✅ PASS' if all_passed else '❌ FAIL'}")
        print("=" * 80)
        print(f"\nPipeline Summary:")
        print(f"  Skill ID: {skill_id}")
        print(f"  Version: {skill_version}")
        print(f"  Folder: {skill_folder.name}/")
        print(f"  ZIP: {zip_path.name}")
        print(f"  Extracted to: {extract_dir.name}/")
        print(f"  Executions: {skill_instance.execution_count}")
        print(f"  Audit events: {len(audit_events)}")
        print(f"  Checksum files: {len(checksum_lines)}")
        print("=" * 80 + "\n")

        assert all_passed, "Gate 2 proof failed: Not all checks passed"


